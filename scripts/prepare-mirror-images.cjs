const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');

// Deterministic, non-generative corrections. Inputs are never overwritten.
const photos = [
  [2, '408aa29b-c0ff-4b05-a4b5-97674c46bcb7/1000028195.jpg', 'castlebar-ornate-mirror-staircase-finished', 'Completed ornate gold-framed mirror above a staircase in Castlebar, beside a crystal chandelier'],
  [1, '70d171c7-ad22-4b8d-8671-22a2a9e5ebbf/1000028192.jpg', 'castlebar-mirror-installation-stair-height', 'View from the stairs showing the installation height of the large gold-framed mirror'],
  [4, 'c7ed00da-a13b-4c99-afa6-4061bf81f6a7/1000028183.jpg', 'castlebar-mirror-landing-side-view', 'Alternative landing view of the finished mirror installation and staircase balustrade'],
  [3, 'c555da83-e3b6-45ab-9486-c5b07141e99d/1000028180.jpg', 'castlebar-mirror-doorway-perspective', 'View through the doorway showing the finished mirror above the stairwell'],
];
const root = path.join(__dirname, '..');
const slug = 'large-mirror-installation-staircase-castlebar';
const hash = b => crypto.createHash('sha256').update(b).digest('hex');
(async () => {
  if (!process.argv[2]) throw Error('Supply the directory containing the five customer attachments');
  const output = path.join(root, 'assets/projects', slug);
  const social = path.join(root, 'social-media', '2026-11-21-castlebar-mirror');
  await fs.mkdir(output, {recursive:true}); await fs.mkdir(social, {recursive:true});
  const images = [], provenance = [];
  for (const [number, input, name, alt] of photos) {
    const source = path.join(process.argv[2], input), original = await fs.readFile(source);
    const {data, info} = await sharp(original).rotate().removeAlpha().toColourspace('srgb').raw().toBuffer({resolveWithObject:true});
    // A gentle luminance curve lifts dark detail and compresses bright light.
    // Tiny blue-channel adjustment reduces the warm cast without neutralising gold.
    const corrected = Buffer.from(data);
    for (let i=0;i<data.length;i+=3) {
      const r=data[i]/255,g=data[i+1]/255,b=data[i+2]/255;
      const y=.2126*r+.7152*g+.0722*b;
      const target=y+.035*y*(1-y)-.045*y**4;
      const scale=y>0?target/y:1;
      corrected[i]=Math.round(Math.min(255,data[i]*scale));
      corrected[i+1]=Math.round(Math.min(255,data[i+1]*scale));
      corrected[i+2]=Math.round(Math.min(255,data[i+2]*scale*1.012));
    }
    const widths=[...new Set([480,800,Math.min(1600,info.width)])].filter(w=>w<=info.width);
    for (const width of widths) await sharp(corrected,{raw:info}).resize({width,withoutEnlargement:true}).webp({quality:82}).toFile(path.join(output,`${name}-${width}.webp`));
    await sharp(corrected,{raw:info}).jpeg({quality:90,mozjpeg:true}).toFile(path.join(social,`${images.length+1}-${name}.jpg`));
    const prefix=`assets/projects/${slug}/${name}`;
    images.push({src:`${prefix}-800.webp`,srcset:widths.map(w=>`${prefix}-${w}.webp ${w}w`).join(', '),full:`${prefix}-${widths.at(-1)}.webp`,alt,width:info.width,height:info.height,position:'center'});
    if(hash(await fs.readFile(source))!==hash(original))throw Error('Original changed');
    provenance.push({customerPhoto:number,sourceFile:path.basename(input),sha256:hash(original),width:info.width,height:info.height,role:images.length===1?'Cover':'Gallery',correction:'Gentle luminance curve; blue channel +1.2%; no crop, perspective warp or generated pixels'});
  }
  await fs.writeFile(path.join(output,'images.json'),JSON.stringify(images,null,2)+'\n');
  await fs.writeFile(path.join(root,'data/mirror-project-images.mjs'),'// Generated by scripts/prepare-mirror-images.cjs; no metadata from originals.\nexport default '+JSON.stringify(images,null,2)+';\n');
  await fs.writeFile(path.join(social,'image-selection.json'),JSON.stringify({permission:'Customer permission confirmed by owner, 21 November 2026',order:[2,1,4,3],excluded:{customerPhoto:5,reason:'Similar angle to photo 1, stronger chandelier flare'},images:provenance},null,2)+'\n');
  console.log('Prepared four photographs, responsive WebP variants and four natural portrait social JPEGs; originals unchanged.');
})().catch(e=>{console.error(e.message);process.exit(1);});
